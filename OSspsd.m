function gout = OSspsd(RPAValues,RPBValues,RQCValues,RQDValues,RWPValues,RWQValues,pValues,qValues,ppqValues,gSSSSNValues)
s_s_s_s_0 = gSSSSNValues(:,1);
s_s_s_s_1 = gSSSSNValues(:,2);
s_s_s_s_2 = gSSSSNValues(:,3);
s_s_s_s_3 = gSSSSNValues(:,4);
PAx = RPAValues(:,1);
PAy = RPAValues(:,2);
PAz = RPAValues(:,3);
PBx = RPBValues(:,1);
PBy = RPBValues(:,2);
PBz = RPBValues(:,3);
QCx = RQCValues(:,1);
QCy = RQCValues(:,2);
QCz = RQCValues(:,3);
QDx = RQDValues(:,1);
QDy = RQDValues(:,2);
QDz = RQDValues(:,3);
WPx = RWPValues(:,1);
WPy = RWPValues(:,2);
WPz = RWPValues(:,3);
WQx = RWQValues(:,1);
WQy = RWQValues(:,2);
WQz = RWQValues(:,3);
ABx = PBx(1)-PAx(1);
ABy = PBy(1)-PAy(1);
ABz = PBz(1)-PAz(1);
CDx = QDx(1)-QCx(1);
CDy = QDy(1)-QCy(1);
CDz = QDz(1)-QCz(1);
oo2p = 0.5./pValues;
oo2q = 0.5./qValues;
qoppq = qValues./ppqValues;
oo2pq = 0.5./ppqValues;
%[ps|ss](0)
px_s_s_s_0 = PAx.*s_s_s_s_0 + WPx.*s_s_s_s_1;
py_s_s_s_0 = PAy.*s_s_s_s_0 + WPy.*s_s_s_s_1;
pz_s_s_s_0 = PAz.*s_s_s_s_0 + WPz.*s_s_s_s_1;
%[ps|ss](1)
px_s_s_s_1 = PAx.*s_s_s_s_1 + WPx.*s_s_s_s_2;
py_s_s_s_1 = PAy.*s_s_s_s_1 + WPy.*s_s_s_s_2;
pz_s_s_s_1 = PAz.*s_s_s_s_1 + WPz.*s_s_s_s_2;
%[ps|ss](2)
px_s_s_s_2 = PAx.*s_s_s_s_2 + WPx.*s_s_s_s_3;
py_s_s_s_2 = PAy.*s_s_s_s_2 + WPy.*s_s_s_s_3;
pz_s_s_s_2 = PAz.*s_s_s_s_2 + WPz.*s_s_s_s_3;
%Contracted (ps|ss)
px_s_s_s = sum(px_s_s_s_0);
py_s_s_s = sum(py_s_s_s_0);
pz_s_s_s = sum(pz_s_s_s_0);
%[ps|ps](0)
px_s_px_s_0 = QCx.*px_s_s_s_0 + WQx.*px_s_s_s_1;
px_s_py_s_0 = QCy.*px_s_s_s_0 + WQy.*px_s_s_s_1;
px_s_pz_s_0 = QCz.*px_s_s_s_0 + WQz.*px_s_s_s_1;
py_s_px_s_0 = QCx.*py_s_s_s_0 + WQx.*py_s_s_s_1;
py_s_py_s_0 = QCy.*py_s_s_s_0 + WQy.*py_s_s_s_1;
py_s_pz_s_0 = QCz.*py_s_s_s_0 + WQz.*py_s_s_s_1;
pz_s_px_s_0 = QCx.*pz_s_s_s_0 + WQx.*pz_s_s_s_1;
pz_s_py_s_0 = QCy.*pz_s_s_s_0 + WQy.*pz_s_s_s_1;
pz_s_pz_s_0 = QCz.*pz_s_s_s_0 + WQz.*pz_s_s_s_1;
%[ps|ps](1)
px_s_px_s_1 = QCx.*px_s_s_s_1 + WQx.*px_s_s_s_2;
px_s_py_s_1 = QCy.*px_s_s_s_1 + WQy.*px_s_s_s_2;
px_s_pz_s_1 = QCz.*px_s_s_s_1 + WQz.*px_s_s_s_2;
py_s_px_s_1 = QCx.*py_s_s_s_1 + WQx.*py_s_s_s_2;
py_s_py_s_1 = QCy.*py_s_s_s_1 + WQy.*py_s_s_s_2;
py_s_pz_s_1 = QCz.*py_s_s_s_1 + WQz.*py_s_s_s_2;
pz_s_px_s_1 = QCx.*pz_s_s_s_1 + WQx.*pz_s_s_s_2;
pz_s_py_s_1 = QCy.*pz_s_s_s_1 + WQy.*pz_s_s_s_2;
pz_s_pz_s_1 = QCz.*pz_s_s_s_1 + WQz.*pz_s_s_s_2;
%Contracted (ps|ps)
px_s_px_s = sum(px_s_px_s_0);
px_s_py_s = sum(px_s_py_s_0);
px_s_pz_s = sum(px_s_pz_s_0);
py_s_px_s = sum(py_s_px_s_0);
py_s_py_s = sum(py_s_py_s_0);
py_s_pz_s = sum(py_s_pz_s_0);
pz_s_px_s = sum(pz_s_px_s_0);
pz_s_py_s = sum(pz_s_py_s_0);
pz_s_pz_s = sum(pz_s_pz_s_0);
%[ps|ds](0)
px_s_dxx_s_0 = QCx.*px_s_px_s_0 + WQx.*px_s_px_s_1 + 1.*oo2q.*(px_s_s_s_0 - qoppq.*px_s_s_s_1);
px_s_dxy_s_0 = QCx.*px_s_py_s_0 + WQx.*px_s_py_s_1;
px_s_dxz_s_0 = QCx.*px_s_pz_s_0 + WQx.*px_s_pz_s_1;
px_s_dyy_s_0 = QCy.*px_s_py_s_0 + WQy.*px_s_py_s_1 + 1.*oo2q.*(px_s_s_s_0 - qoppq.*px_s_s_s_1);
px_s_dyz_s_0 = QCy.*px_s_pz_s_0 + WQy.*px_s_pz_s_1;
px_s_dzz_s_0 = QCz.*px_s_pz_s_0 + WQz.*px_s_pz_s_1 + 1.*oo2q.*(px_s_s_s_0 - qoppq.*px_s_s_s_1);
py_s_dxx_s_0 = QCx.*py_s_px_s_0 + WQx.*py_s_px_s_1 + 1.*oo2q.*(py_s_s_s_0 - qoppq.*py_s_s_s_1);
py_s_dxy_s_0 = QCx.*py_s_py_s_0 + WQx.*py_s_py_s_1;
py_s_dxz_s_0 = QCx.*py_s_pz_s_0 + WQx.*py_s_pz_s_1;
py_s_dyy_s_0 = QCy.*py_s_py_s_0 + WQy.*py_s_py_s_1 + 1.*oo2q.*(py_s_s_s_0 - qoppq.*py_s_s_s_1);
py_s_dyz_s_0 = QCy.*py_s_pz_s_0 + WQy.*py_s_pz_s_1;
py_s_dzz_s_0 = QCz.*py_s_pz_s_0 + WQz.*py_s_pz_s_1 + 1.*oo2q.*(py_s_s_s_0 - qoppq.*py_s_s_s_1);
pz_s_dxx_s_0 = QCx.*pz_s_px_s_0 + WQx.*pz_s_px_s_1 + 1.*oo2q.*(pz_s_s_s_0 - qoppq.*pz_s_s_s_1);
pz_s_dxy_s_0 = QCx.*pz_s_py_s_0 + WQx.*pz_s_py_s_1;
pz_s_dxz_s_0 = QCx.*pz_s_pz_s_0 + WQx.*pz_s_pz_s_1;
pz_s_dyy_s_0 = QCy.*pz_s_py_s_0 + WQy.*pz_s_py_s_1 + 1.*oo2q.*(pz_s_s_s_0 - qoppq.*pz_s_s_s_1);
pz_s_dyz_s_0 = QCy.*pz_s_pz_s_0 + WQy.*pz_s_pz_s_1;
pz_s_dzz_s_0 = QCz.*pz_s_pz_s_0 + WQz.*pz_s_pz_s_1 + 1.*oo2q.*(pz_s_s_s_0 - qoppq.*pz_s_s_s_1);
%Contracted (ps|ds)
px_s_dxx_s = sum(px_s_dxx_s_0);
px_s_dxy_s = sum(px_s_dxy_s_0);
px_s_dxz_s = sum(px_s_dxz_s_0);
px_s_dyy_s = sum(px_s_dyy_s_0);
px_s_dyz_s = sum(px_s_dyz_s_0);
px_s_dzz_s = sum(px_s_dzz_s_0);
py_s_dxx_s = sum(py_s_dxx_s_0);
py_s_dxy_s = sum(py_s_dxy_s_0);
py_s_dxz_s = sum(py_s_dxz_s_0);
py_s_dyy_s = sum(py_s_dyy_s_0);
py_s_dyz_s = sum(py_s_dyz_s_0);
py_s_dzz_s = sum(py_s_dzz_s_0);
pz_s_dxx_s = sum(pz_s_dxx_s_0);
pz_s_dxy_s = sum(pz_s_dxy_s_0);
pz_s_dxz_s = sum(pz_s_dxz_s_0);
pz_s_dyy_s = sum(pz_s_dyy_s_0);
pz_s_dyz_s = sum(pz_s_dyz_s_0);
pz_s_dzz_s = sum(pz_s_dzz_s_0);
%(ps|pp) from horizontal recursion on the ket 
px_s_px_px = CDx*px_s_px_s + px_s_dxx_s;
px_s_px_py = CDy*px_s_px_s + px_s_dxy_s;
px_s_px_pz = CDz*px_s_px_s + px_s_dxz_s;
px_s_py_px = CDx*px_s_py_s + px_s_dxy_s;
px_s_py_py = CDy*px_s_py_s + px_s_dyy_s;
px_s_py_pz = CDz*px_s_py_s + px_s_dyz_s;
px_s_pz_px = CDx*px_s_pz_s + px_s_dxz_s;
px_s_pz_py = CDy*px_s_pz_s + px_s_dyz_s;
px_s_pz_pz = CDz*px_s_pz_s + px_s_dzz_s;
py_s_px_px = CDx*py_s_px_s + py_s_dxx_s;
py_s_px_py = CDy*py_s_px_s + py_s_dxy_s;
py_s_px_pz = CDz*py_s_px_s + py_s_dxz_s;
py_s_py_px = CDx*py_s_py_s + py_s_dxy_s;
py_s_py_py = CDy*py_s_py_s + py_s_dyy_s;
py_s_py_pz = CDz*py_s_py_s + py_s_dyz_s;
py_s_pz_px = CDx*py_s_pz_s + py_s_dxz_s;
py_s_pz_py = CDy*py_s_pz_s + py_s_dyz_s;
py_s_pz_pz = CDz*py_s_pz_s + py_s_dzz_s;
pz_s_px_px = CDx*pz_s_px_s + pz_s_dxx_s;
pz_s_px_py = CDy*pz_s_px_s + pz_s_dxy_s;
pz_s_px_pz = CDz*pz_s_px_s + pz_s_dxz_s;
pz_s_py_px = CDx*pz_s_py_s + pz_s_dxy_s;
pz_s_py_py = CDy*pz_s_py_s + pz_s_dyy_s;
pz_s_py_pz = CDz*pz_s_py_s + pz_s_dyz_s;
pz_s_pz_px = CDx*pz_s_pz_s + pz_s_dxz_s;
pz_s_pz_py = CDy*pz_s_pz_s + pz_s_dyz_s;
pz_s_pz_pz = CDz*pz_s_pz_s + pz_s_dzz_s;
%(sp|sd) from horizontal recursion on the bra 
s_px_s_dxx = ABx*s_s_s_dxx + px_s_s_dxx;
s_px_s_dxy = ABx*s_s_s_dxy + px_s_s_dxy;
s_px_s_dxz = ABx*s_s_s_dxz + px_s_s_dxz;
s_px_s_dyy = ABx*s_s_s_dyy + px_s_s_dyy;
s_px_s_dyz = ABx*s_s_s_dyz + px_s_s_dyz;
s_px_s_dzz = ABx*s_s_s_dzz + px_s_s_dzz;
s_py_s_dxx = ABy*s_s_s_dxx + py_s_s_dxx;
s_py_s_dxy = ABy*s_s_s_dxy + py_s_s_dxy;
s_py_s_dxz = ABy*s_s_s_dxz + py_s_s_dxz;
s_py_s_dyy = ABy*s_s_s_dyy + py_s_s_dyy;
s_py_s_dyz = ABy*s_s_s_dyz + py_s_s_dyz;
s_py_s_dzz = ABy*s_s_s_dzz + py_s_s_dzz;
s_pz_s_dxx = ABz*s_s_s_dxx + pz_s_s_dxx;
s_pz_s_dxy = ABz*s_s_s_dxy + pz_s_s_dxy;
s_pz_s_dxz = ABz*s_s_s_dxz + pz_s_s_dxz;
s_pz_s_dyy = ABz*s_s_s_dyy + pz_s_s_dyy;
s_pz_s_dyz = ABz*s_s_s_dyz + pz_s_s_dyz;
s_pz_s_dzz = ABz*s_s_s_dzz + pz_s_s_dzz;
gout = zeros(1,3,1,6);
gout(1,1,1,1) = s_px_s_dxx;
gout(1,1,1,2) = s_px_s_dxy;
gout(1,1,1,3) = s_px_s_dxz;
gout(1,1,1,4) = s_px_s_dyy;
gout(1,1,1,5) = s_px_s_dyz;
gout(1,1,1,6) = s_px_s_dzz;
gout(1,2,1,1) = s_py_s_dxx;
gout(1,2,1,2) = s_py_s_dxy;
gout(1,2,1,3) = s_py_s_dxz;
gout(1,2,1,4) = s_py_s_dyy;
gout(1,2,1,5) = s_py_s_dyz;
gout(1,2,1,6) = s_py_s_dzz;
gout(1,3,1,1) = s_pz_s_dxx;
gout(1,3,1,2) = s_pz_s_dxy;
gout(1,3,1,3) = s_pz_s_dxz;
gout(1,3,1,4) = s_pz_s_dyy;
gout(1,3,1,5) = s_pz_s_dyz;
gout(1,3,1,6) = s_pz_s_dzz;
end