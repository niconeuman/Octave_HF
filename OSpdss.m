function gout = OSpdss(RPAValues,RPBValues,RQCValues,RQDValues,RWPValues,RWQValues,pValues,qValues,ppqValues,gSSSSNValues)
s_s_s_s_0 = gSSSSNValues(:,1);
s_s_s_s_1 = gSSSSNValues(:,2);
s_s_s_s_2 = gSSSSNValues(:,3);
s_s_s_s_3 = gSSSSNValues(:,4);
PAx = RPAValues(:,1);
PAy = RPAValues(:,2);
PAz = RPAValues(:,3);
PBx = RPBValues(:,1);
PBy = RPBValues(:,2);
PBz = RPBValues(:,3);
QCx = RQCValues(:,1);
QCy = RQCValues(:,2);
QCz = RQCValues(:,3);
QDx = RQDValues(:,1);
QDy = RQDValues(:,2);
QDz = RQDValues(:,3);
WPx = RWPValues(:,1);
WPy = RWPValues(:,2);
WPz = RWPValues(:,3);
WQx = RWQValues(:,1);
WQy = RWQValues(:,2);
WQz = RWQValues(:,3);
ABx = PBx(1)-PAx(1);
ABy = PBy(1)-PAy(1);
ABz = PBz(1)-PAz(1);
CDx = QDx(1)-QCx(1);
CDy = QDy(1)-QCy(1);
CDz = QDz(1)-QCz(1);
oo2p = 0.5./pValues;
oo2q = 0.5./qValues;
qoppq = qValues./ppqValues;
oo2pq = 0.5./ppqValues;
%[ps|ss](0)
px_s_s_s_0 = PAx.*s_s_s_s_0 + WPx.*s_s_s_s_1;
py_s_s_s_0 = PAy.*s_s_s_s_0 + WPy.*s_s_s_s_1;
pz_s_s_s_0 = PAz.*s_s_s_s_0 + WPz.*s_s_s_s_1;
%[ps|ss](1)
px_s_s_s_1 = PAx.*s_s_s_s_1 + WPx.*s_s_s_s_2;
py_s_s_s_1 = PAy.*s_s_s_s_1 + WPy.*s_s_s_s_2;
pz_s_s_s_1 = PAz.*s_s_s_s_1 + WPz.*s_s_s_s_2;
%[ps|ss](2)
px_s_s_s_2 = PAx.*s_s_s_s_2 + WPx.*s_s_s_s_3;
py_s_s_s_2 = PAy.*s_s_s_s_2 + WPy.*s_s_s_s_3;
pz_s_s_s_2 = PAz.*s_s_s_s_2 + WPz.*s_s_s_s_3;
%Contracted (ps|ss)
px_s_s_s = sum(px_s_s_s_0);
py_s_s_s = sum(py_s_s_s_0);
pz_s_s_s = sum(pz_s_s_s_0);
%[ds|ss](0)
dxx_s_s_s_0 = PAx.*px_s_s_s_0 + WPx.*px_s_s_s_1 + 1.*oo2p.*(s_s_s_s_0 - qoppq.*s_s_s_s_1);
dxy_s_s_s_0 = PAx.*py_s_s_s_0 + WPx.*py_s_s_s_1;
dxz_s_s_s_0 = PAx.*pz_s_s_s_0 + WPx.*pz_s_s_s_1;
dyy_s_s_s_0 = PAy.*py_s_s_s_0 + WPy.*py_s_s_s_1 + 1.*oo2p.*(s_s_s_s_0 - qoppq.*s_s_s_s_1);
dyz_s_s_s_0 = PAy.*pz_s_s_s_0 + WPy.*pz_s_s_s_1;
dzz_s_s_s_0 = PAz.*pz_s_s_s_0 + WPz.*pz_s_s_s_1 + 1.*oo2p.*(s_s_s_s_0 - qoppq.*s_s_s_s_1);
%[ds|ss](1)
dxx_s_s_s_1 = PAx.*px_s_s_s_1 + WPx.*px_s_s_s_2 + 1.*oo2p.*(s_s_s_s_1 - qoppq.*s_s_s_s_2);
dxy_s_s_s_1 = PAx.*py_s_s_s_1 + WPx.*py_s_s_s_2;
dxz_s_s_s_1 = PAx.*pz_s_s_s_1 + WPx.*pz_s_s_s_2;
dyy_s_s_s_1 = PAy.*py_s_s_s_1 + WPy.*py_s_s_s_2 + 1.*oo2p.*(s_s_s_s_1 - qoppq.*s_s_s_s_2);
dyz_s_s_s_1 = PAy.*pz_s_s_s_1 + WPy.*pz_s_s_s_2;
dzz_s_s_s_1 = PAz.*pz_s_s_s_1 + WPz.*pz_s_s_s_2 + 1.*oo2p.*(s_s_s_s_1 - qoppq.*s_s_s_s_2);
%Contracted (ds|ss)
dxx_s_s_s = sum(dxx_s_s_s_0);
dxy_s_s_s = sum(dxy_s_s_s_0);
dxz_s_s_s = sum(dxz_s_s_s_0);
dyy_s_s_s = sum(dyy_s_s_s_0);
dyz_s_s_s = sum(dyz_s_s_s_0);
dzz_s_s_s = sum(dzz_s_s_s_0);
%[fs|ss](0)
fxxx_s_s_s_0 = PAx.*dxx_s_s_s_0 + WPx.*dxx_s_s_s_1 + 2.*oo2p.*(px_s_s_s_0 - qoppq.*px_s_s_s_1);
fxxy_s_s_s_0 = PAy.*dxx_s_s_s_0 + WPy.*dxx_s_s_s_1;
fxxz_s_s_s_0 = PAz.*dxx_s_s_s_0 + WPz.*dxx_s_s_s_1;
fxyy_s_s_s_0 = PAx.*dyy_s_s_s_0 + WPx.*dyy_s_s_s_1;
fxyz_s_s_s_0 = PAx.*dyz_s_s_s_0 + WPx.*dyz_s_s_s_1;
fxzz_s_s_s_0 = PAx.*dzz_s_s_s_0 + WPx.*dzz_s_s_s_1;
fyyy_s_s_s_0 = PAy.*dyy_s_s_s_0 + WPy.*dyy_s_s_s_1 + 2.*oo2p.*(py_s_s_s_0 - qoppq.*py_s_s_s_1);
fyyz_s_s_s_0 = PAz.*dyy_s_s_s_0 + WPz.*dyy_s_s_s_1;
fyzz_s_s_s_0 = PAy.*dzz_s_s_s_0 + WPy.*dzz_s_s_s_1;
fzzz_s_s_s_0 = PAz.*dzz_s_s_s_0 + WPz.*dzz_s_s_s_1 + 2.*oo2p.*(pz_s_s_s_0 - qoppq.*pz_s_s_s_1);
%Contracted (fs|ss)
fxxx_s_s_s = sum(fxxx_s_s_s_0);
fxxy_s_s_s = sum(fxxy_s_s_s_0);
fxxz_s_s_s = sum(fxxz_s_s_s_0);
fxyy_s_s_s = sum(fxyy_s_s_s_0);
fxyz_s_s_s = sum(fxyz_s_s_s_0);
fxzz_s_s_s = sum(fxzz_s_s_s_0);
fyyy_s_s_s = sum(fyyy_s_s_s_0);
fyyz_s_s_s = sum(fyyz_s_s_s_0);
fyzz_s_s_s = sum(fyzz_s_s_s_0);
fzzz_s_s_s = sum(fzzz_s_s_s_0);
%(pp|ss) from horizontal recursion on the bra 
px_px_s_s = ABx*px_s_s_s + dxx_s_s_s;
px_py_s_s = ABy*px_s_s_s + dxy_s_s_s;
px_pz_s_s = ABz*px_s_s_s + dxz_s_s_s;
py_px_s_s = ABx*py_s_s_s + dxy_s_s_s;
py_py_s_s = ABy*py_s_s_s + dyy_s_s_s;
py_pz_s_s = ABz*py_s_s_s + dyz_s_s_s;
pz_px_s_s = ABx*pz_s_s_s + dxz_s_s_s;
pz_py_s_s = ABy*pz_s_s_s + dyz_s_s_s;
pz_pz_s_s = ABz*pz_s_s_s + dzz_s_s_s;
%(dp|ss) from horizontal recursion on the bra 
dxx_px_s_s = ABx*dxx_s_s_s + fxxx_s_s_s;
dxx_py_s_s = ABy*dxx_s_s_s + fxxy_s_s_s;
dxx_pz_s_s = ABz*dxx_s_s_s + fxxz_s_s_s;
dxy_px_s_s = ABx*dxy_s_s_s + fxxy_s_s_s;
dxy_py_s_s = ABy*dxy_s_s_s + fxyy_s_s_s;
dxy_pz_s_s = ABz*dxy_s_s_s + fxyz_s_s_s;
dxz_px_s_s = ABx*dxz_s_s_s + fxxz_s_s_s;
dxz_py_s_s = ABy*dxz_s_s_s + fxyz_s_s_s;
dxz_pz_s_s = ABz*dxz_s_s_s + fxzz_s_s_s;
dyy_px_s_s = ABx*dyy_s_s_s + fxyy_s_s_s;
dyy_py_s_s = ABy*dyy_s_s_s + fyyy_s_s_s;
dyy_pz_s_s = ABz*dyy_s_s_s + fyyz_s_s_s;
dyz_px_s_s = ABx*dyz_s_s_s + fxyz_s_s_s;
dyz_py_s_s = ABy*dyz_s_s_s + fyyz_s_s_s;
dyz_pz_s_s = ABz*dyz_s_s_s + fyzz_s_s_s;
dzz_px_s_s = ABx*dzz_s_s_s + fxzz_s_s_s;
dzz_py_s_s = ABy*dzz_s_s_s + fyzz_s_s_s;
dzz_pz_s_s = ABz*dzz_s_s_s + fzzz_s_s_s;
%(pd|ss) from horizontal recursion on the bra 
px_dxx_s_s = ABx*px_px_s_s + dxx_px_s_s;
px_dxy_s_s = ABx*px_py_s_s + dxx_py_s_s;
px_dxz_s_s = ABx*px_pz_s_s + dxx_pz_s_s;
px_dyy_s_s = ABy*px_py_s_s + dxy_py_s_s;
px_dyz_s_s = ABy*px_pz_s_s + dxy_pz_s_s;
px_dzz_s_s = ABz*px_pz_s_s + dxz_pz_s_s;
py_dxx_s_s = ABx*py_px_s_s + dxy_px_s_s;
py_dxy_s_s = ABx*py_py_s_s + dxy_py_s_s;
py_dxz_s_s = ABx*py_pz_s_s + dxy_pz_s_s;
py_dyy_s_s = ABy*py_py_s_s + dyy_py_s_s;
py_dyz_s_s = ABy*py_pz_s_s + dyy_pz_s_s;
py_dzz_s_s = ABz*py_pz_s_s + dyz_pz_s_s;
pz_dxx_s_s = ABx*pz_px_s_s + dxz_px_s_s;
pz_dxy_s_s = ABx*pz_py_s_s + dxz_py_s_s;
pz_dxz_s_s = ABx*pz_pz_s_s + dxz_pz_s_s;
pz_dyy_s_s = ABy*pz_py_s_s + dyz_py_s_s;
pz_dyz_s_s = ABy*pz_pz_s_s + dyz_pz_s_s;
pz_dzz_s_s = ABz*pz_pz_s_s + dzz_pz_s_s;
gout = zeros(3,6,1,1);
gout(1,1,1,1) = px_dxx_s_s;
gout(1,2,1,1) = px_dxy_s_s;
gout(1,3,1,1) = px_dxz_s_s;
gout(1,4,1,1) = px_dyy_s_s;
gout(1,5,1,1) = px_dyz_s_s;
gout(1,6,1,1) = px_dzz_s_s;
gout(2,1,1,1) = py_dxx_s_s;
gout(2,2,1,1) = py_dxy_s_s;
gout(2,3,1,1) = py_dxz_s_s;
gout(2,4,1,1) = py_dyy_s_s;
gout(2,5,1,1) = py_dyz_s_s;
gout(2,6,1,1) = py_dzz_s_s;
gout(3,1,1,1) = pz_dxx_s_s;
gout(3,2,1,1) = pz_dxy_s_s;
gout(3,3,1,1) = pz_dxz_s_s;
gout(3,4,1,1) = pz_dyy_s_s;
gout(3,5,1,1) = pz_dyz_s_s;
gout(3,6,1,1) = pz_dzz_s_s;
end